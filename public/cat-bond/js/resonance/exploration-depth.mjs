// Clip only the lower portion of a nearby actor. This is a gameplay-safe
// occlusion budget: the protagonist's head always remains readable.
function clipBelow(poly,y){
 const out=[];for(let i=0;i<poly.length;i++){const a=poly[i],b=poly[(i+1)%poly.length],ai=a[1]>=y,bi=b[1]>=y;if(ai)out.push(a);if(ai!==bi){const t=(y-a[1])/(b[1]-a[1]);out.push([a[0]+(b[0]-a[0])*t,y]);}}return out;
}
export function foregroundCuts(asset,fit,x,y,s=1){
 const key=String(asset||'').split('/').pop().split('?')[0].replace(/\.webp$/,'');
 if(!fit||fit.width<=0||fit.height<=0||!Number.isFinite(x)||!Number.isFinite(y)||!(s>0))return [];
 const out=[],foot=(y-fit.y)/fit.height,minY=(y-54*s-fit.y)/fit.height;
 for(const layer of masks[key]||[]){
  if(foot>layer.base+.008||layer.base-foot>.20)continue;
  const p=clipBelow(layer.points,minY);
  if(p.length<3)continue;
  const q=p.map(([u,v])=>[fit.x+u*fit.width,fit.y+v*fit.height]);
  if(Math.min(...q.map(p=>p[0]))>x+34*s||Math.max(...q.map(p=>p[0]))<x-34*s||Math.min(...q.map(p=>p[1]))>y+4*s||Math.max(...q.map(p=>p[1]))<y-54*s)continue;
  out.push(q);
 }return out;
}
export function depthScale(y){return .87+.24*Math.max(0,Math.min(1,y));}
export function withForeground(ctx,asset,fit,x,y,s,draw){
 const cuts=foregroundCuts(asset,fit,x,y,s);
 if(!cuts.length)return draw();
 ctx.save();try{
  // Clip the actor, not the original painting. The exact original foreground
  // pixels remain underneath; multiple overlapping layers are intersected.
  for(const p of cuts){ctx.beginPath();ctx.rect(fit.x-fit.width,fit.y-fit.height,fit.width*3,fit.height*3);ctx.moveTo(...p[0]);for(const v of p.slice(1))ctx.lineTo(...v);ctx.closePath();ctx.clip('evenodd');}
  return draw();
 }finally{ctx.restore();}
}
