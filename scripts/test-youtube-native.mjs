import assert from 'node:assert/strict';
import fs from 'node:fs';
import {ytOverlay,nativeYouTubeSnapshot} from '../src/youtube-native.js';
const base=JSON.parse(fs.readFileSync('promotion/social-metrics-snapshot.json','utf8'));
const approved=base.metricScope.verifiedPosts.filter(x=>x.platform==='youtube');
assert.equal(approved.length,7);
assert.ok(approved.find(x=>x.game==='cat-bond')?.url.endsWith('/JoDtL_gIk4M'));
assert.ok(!JSON.stringify(approved).includes('ELv02K9K294'));
const state={checkedAt:'2026-11-22T23:45:00.000Z',posts:approved.map((p,i)=>({...p,views:i+3,likes:i,comments:0,dataSource:'youtube-data-api-v3'}))};
const o=ytOverlay(base,state,'ready');
assert.equal(o.platforms.find(p=>p.id==='youtube').views,42);
assert.equal(o.metricScope.verifiedPosts.length,base.metricScope.verifiedPosts.length);
assert.equal(o.nativeYouTube.postMetricsCount,7);
assert.equal(o.metricScope.verifiedPosts.filter(p=>p.platform==='youtube'&&p.dataSource==='youtube-data-api-v3').length,7);
const partial=ytOverlay(base,{...state,posts:state.posts.slice(0,2)},'ready');
assert.equal(partial.platforms.find(p=>p.id==='youtube').views,null);
assert.equal(partial.metricScope.verifiedPosts.find(p=>p.platform==='youtube'&&p.game==='tiny-town').views,null);
const missing=ytOverlay(base,null,'needs_api_key');
assert.equal(missing.nativeYouTube.status,'needs_api_key');
assert.equal(missing.platforms.find(p=>p.id==='youtube').views,null);
assert.equal((await nativeYouTubeSnapshot({},base)).nativeYouTube.status,'needs_api_key');
console.log('YouTube official seven-video allowlist and incomplete feed handling passed.');
