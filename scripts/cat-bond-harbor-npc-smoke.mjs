import {chromium} from 'playwright';
import assert from 'node:assert/strict';
import fs from 'node:fs';
fs.mkdirSync('artifacts/cat-bond-harbor-npc',{recursive:true});
const origin=process.env.CAT_BOND_ORIGIN||'http://127.0.0.1:8765';
const browser=await chromium.launch({headless:true,args:['--no-sandbox']});
const errors=[];
async function start(viewport,isMobile,locale){
 const context=await browser.newContext({viewport,deviceScaleFactor:isMobile?2:1,isMobile,hasTouch:isMobile});
 const page=await context.newPage();page.on('pageerror',e=>errors.push(e.message));
 await page.goto(origin+'/cat-bond/?autodev=1&lang='+locale,{waitUntil:'domcontentloaded',timeout:30000});
 await page.waitForFunction(()=>!!window.__game&&window.__game._lastTs>0, null,{timeout:15000});
 await page.locator('#cb-harbor-story-open').waitFor({state:'visible',timeout:10000});
 assert.equal(await page.evaluate(()=>window.MorrowwishI18n.get()),locale);
 await page.locator('#cb-harbor-story-open').click();
 await page.locator('.cb-harbor-story:not([hidden])').waitFor();
 await page.waitForFunction(()=>document.querySelector('.cb-harbor-portrait')?.naturalWidth>100);
 assert.equal(await page.evaluate(()=>window.__game.scene),'story');
 return {context,page};
}
try{
 const desktop=await start({width:1440,height:900},false,'en');
 const page=desktop.page;
 assert.match(await page.locator('.cb-harbor-line').textContent(),/If the light comes on/);
 const before=await page.locator('.cb-harbor-line').textContent();
 await page.locator('[data-action="language"]').click();
 await page.waitForFunction(()=>document.querySelector('.cb-harbor-line')?.textContent.includes('灯亮了'));
 await page.locator('[data-action="language"]').click();
 await page.waitForFunction(()=>document.querySelector('.cb-harbor-line')?.textContent.includes('If the light comes on'));
 const box=await page.locator('.cb-harbor-dialogue').boundingBox();
 assert.ok(box&&box.x>=0&&box.y>=0&&box.x+box.width<=1440&&box.y+box.height<=900,'Desktop dialogue panel outside viewport');
 await page.screenshot({path:'artifacts/cat-bond-harbor-npc/desktop-dialogue.png'});
 for(let i=0;i<5;i++)await page.locator('[data-action="next"]').click();
 await page.locator('.cb-harbor-choices:not([hidden])').waitFor();
 assert.equal(await page.locator('.cb-harbor-choice').count(),2);
 await page.getByRole('button',{name:'Comfort Qilan first'}).click();
 assert.equal(await page.evaluate(()=>window.State.S.npcStories.harborKeeper.trust.qilan),2);
 assert.equal(await page.evaluate(()=>window.State.S.npcStories.harborKeeper.supportRoute),'navigator-first');
 assert.equal(await page.evaluate(()=>window.State.S.npcStories.harborKeeper.quest.id),'harbor:flooded-logbook');
 assert.equal(await page.evaluate(()=>window.State.S.npcStories.harborKeeper.event.id),'harbor:H-02:keeper-choice');
 for(let i=0;i<3;i++)await page.locator('[data-action="next"]').click();
 await page.locator('.cb-harbor-quest:not([hidden])').waitFor();
 assert.match(await page.locator('.cb-harbor-quest h3').textContent(),/Flooded Logbook/);
 assert.equal(await page.locator('#cb-harbor-quest-tracker').isVisible(),true);
 assert.equal(await page.evaluate(()=>window.__game.scene),'story');
 await page.screenshot({path:'artifacts/cat-bond-harbor-npc/desktop-quest.png'});
 await desktop.context.close();

 const mobile=await start({width:390,height:844},true,'zh');
 const phone=mobile.page;
 assert.match(await phone.locator('.cb-harbor-line').textContent(),/灯亮了/);
 const dimensions=await phone.evaluate(()=>({width:innerWidth,scrollWidth:document.documentElement.scrollWidth,stage:document.querySelector('#stage').getBoundingClientRect().toJSON(),dialogue:document.querySelector('.cb-harbor-dialogue').getBoundingClientRect().toJSON(),portrait:document.querySelector('.cb-harbor-portrait').getBoundingClientRect().toJSON()}));
 assert.ok(dimensions.scrollWidth<=dimensions.width+2,'Mobile horizontal overflow '+JSON.stringify(dimensions));
 assert.ok(dimensions.dialogue.width<=dimensions.width&&dimensions.dialogue.height<430,'Mobile dialogue sizing '+JSON.stringify(dimensions));
 await phone.screenshot({path:'artifacts/cat-bond-harbor-npc/mobile-dialogue.png'});
 for(let i=0;i<5;i++)await phone.locator('[data-action="next"]').click();
 await phone.locator('.cb-harbor-choices:not([hidden])').waitFor();
 await phone.getByRole('button',{name:'先询问岬灯过去的风暴'}).click();
 assert.equal(await phone.evaluate(()=>window.State.S.npcStories.harborKeeper.trust.jiedeng),2);
 assert.equal(await phone.evaluate(()=>window.State.S.npcStories.harborKeeper.supportRoute),'keeper-first');
 for(let i=0;i<3;i++)await phone.locator('[data-action="next"]').click();
 await phone.locator('.cb-harbor-quest:not([hidden])').waitFor();
 await phone.screenshot({path:'artifacts/cat-bond-harbor-npc/mobile-quest.png'});
 await mobile.context.close();
 assert.deepEqual(errors,[],'Browser runtime errors: '+errors.join('; '));
 console.log('HARBOR NPC BROWSER QA PASS: desktop + mobile; dialogue, language switch, two branches, trust, quest, event, save state, portrait loads. Screenshots in artifacts/cat-bond-harbor-npc/.');
}finally{await browser.close();}
