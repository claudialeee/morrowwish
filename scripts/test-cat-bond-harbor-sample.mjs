import assert from "node:assert/strict";
import {campaign} from "../public/cat-bond/js/resonance/campaign.mjs";
import {BRANCH_DIALOGUE,createHarborState,advanceHarborState,chooseHarborState,normalizeHarborState} from "../public/cat-bond/js/resonance/harbor-sample-state.mjs";
const scene=campaign.scenes.find(s=>s.id==="harbor:H-02");
assert.equal(scene.lines.length,5);
assert.equal(scene.choices.length,2);
assert.equal(scene.lines[0].speaker,"jiedeng");
let s=createHarborState();
for(let i=0;i<5;i++)s=advanceHarborState(s);
assert.equal(s.stage,"choice");
const comfort=chooseHarborState(s,"comfort");
assert.equal(comfort.trust.qilan,2);
assert.equal(comfort.trust.jiedeng,0);
assert.equal(comfort.supportRoute,"navigator-first");
assert.equal(comfort.quest.id,"harbor:flooded-logbook");
assert.equal(comfort.event.id,"harbor:H-02:keeper-choice");
let c=comfort;
for(let i=0;i<3;i++)c=advanceHarborState(c);
assert.equal(c.stage,"quest");
assert.equal(BRANCH_DIALOGUE.comfort.length,3);
const ask=chooseHarborState(s,"ask");
assert.equal(ask.trust.jiedeng,2);
assert.equal(ask.supportRoute,"keeper-first");
assert.notDeepEqual(BRANCH_DIALOGUE.comfort,BRANCH_DIALOGUE.ask);
assert.equal(chooseHarborState(comfort,"ask"),null);
assert.deepEqual(normalizeHarborState(JSON.parse(JSON.stringify(ask))),ask);
console.log("Harbor NPC sample PASS", {officialLines:scene.lines.length,choices:scene.choices.length,branchLines:6,saveRestore:true,quest:comfort.quest.id});
