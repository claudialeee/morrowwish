import assert from "node:assert/strict";
import {campaign} from "../public/cat-bond/js/resonance/campaign.mjs";
import {harborSample} from "../public/cat-bond/js/resonance/harbor-sample-data.mjs";
import {BRANCH_DIALOGUE,createHarborState,advanceHarborState,chooseHarborState,normalizeHarborState} from "../public/cat-bond/js/resonance/harbor-sample-state.mjs";
const canonical=campaign.scenes.find(s=>s.id==="harbor:H-02");
assert.deepEqual(harborSample.scene.lines,canonical.lines,"H-02 lines must stay canonical");
assert.deepEqual(harborSample.scene.choices,canonical.choices,"H-02 choices must stay canonical");
assert.equal(harborSample.scene.lines.length,5);
let s=createHarborState();for(let i=0;i<5;i++)s=advanceHarborState(s);assert.equal(s.stage,"choice");
const comfort=chooseHarborState(s,"comfort"),ask=chooseHarborState(s,"ask");
assert.equal(comfort.trust.qilan,2);assert.equal(comfort.trust.jiedeng,0);assert.equal(comfort.supportRoute,"navigator-first");
assert.equal(ask.trust.jiedeng,2);assert.equal(ask.trust.qilan,0);assert.equal(ask.supportRoute,"keeper-first");
assert.equal(comfort.quest.id,"harbor:flooded-logbook");assert.equal(comfort.event.id,"harbor:H-02:keeper-choice");
let done=comfort;for(let i=0;i<3;i++)done=advanceHarborState(done);assert.equal(done.stage,"quest");
assert.equal(BRANCH_DIALOGUE.comfort.length,3);assert.equal(BRANCH_DIALOGUE.ask.length,3);
assert.equal(chooseHarborState(comfort,"ask"),null);
assert.deepEqual(normalizeHarborState(JSON.parse(JSON.stringify(ask))),ask);
console.log("Harbor NPC state PASS",{canonicalH02:5,choices:2,branchLines:6,saveRestore:true,quest:true,event:true});
